// Optional release signing: provide keystore.properties (local) or the
// SIGNING_* environment variables (CI). Without them the release build is
// produced unsigned (app-release-unsigned.apk) and must be signed before install.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(key: String, env: String): String? =
    keystoreProps.getProperty(key) ?: System.getenv(env)

